import { error } from '@sveltejs/kit'

import { type as arktype } from 'arktype'

import { parseEntitySelector } from '$/schema/$schema.ts'
import EntitySchema from '$/schema/AvalancheValidator_Timestamp.ts'
import { schema } from '$/schema/index.ts'

import type { PageLoad } from './$types.ts'


export const load: PageLoad = ({ params }) => {
	const selector = parseEntitySelector(
		schema,
		EntitySchema,
		{
			'$validator': {
				nodeId: decodeURIComponent(params.nodeId),
				subnetId: decodeURIComponent(params.subnetId),
				startTimeMs: decodeURIComponent(params.startTimeMs),
			},
			timestampMs: Number(params.timestampMs),
			source: decodeURIComponent(params.source),
		}
	)
	if (selector instanceof arktype.errors) error(404, 'Invalid AvalancheValidator_Timestamp selector')

	return { selector }
}
